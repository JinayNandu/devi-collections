#!/usr/bin/perl
# Build the Claude Artifact copy of the page.
#
#   perl tools/mkartifact.pl
#   -> build/artifact.html
#
# ---------------------------------------------------------------------------
# WHY THIS EXISTS RATHER THAN A SECOND index.html BY HAND
#
# The artifact host wraps whatever you publish in its OWN
# <!doctype html><head>…</head><body> skeleton, so the published page must not
# carry those tags itself. That is the only difference from app/index.html,
# and keeping a hand-edited duplicate in sync is exactly the kind of thing
# that silently drifts -- railsathi has already been bitten once by a
# master/deploy data split going stale in the wrong direction.
#
# So the artifact page is GENERATED, every time, from the real one. There is
# one index.html in this project and this script is a view of it.
#
# Two transforms:
#   1. Strip doctype / <html> / <head> / <body>, lifting <title>, the font
#      <link> and the viewport-fit meta to the top of the fragment.
#   2. INLINE the five stylesheets into one <style>. The host's CSP admits
#      external stylesheets only from fonts.googleapis.com; our own published
#      files are same-origin and would be fine, but inlining removes five
#      round trips and any argument about it.
#
# JavaScript stays as separate module files published alongside, because ES
# modules need real URLs and the import graph is the architecture.
# ---------------------------------------------------------------------------
use strict;
use warnings;

my $root = $0; $root =~ s{[/\\]tools[/\\]mkartifact\.pl$}{};
$root = '.' if $root eq $0;
my $APP = "$root/app";
my $OUT = "$root/build";

mkdir $OUT unless -d $OUT;

sub slurp {
  my ($p) = @_;
  open my $fh, '<:encoding(UTF-8)', $p or die "cannot read $p: $!\n";
  local $/; my $t = <$fh>; close $fh;
  return $t;
}

my $html = slurp("$APP/index.html");

# ---- the pieces we keep from <head> ---------------------------------------
# The artifact gallery wants a NAME -- two to four words, not a name plus the
# tagline after a dash, which reads as generated filler beside other cards.
# The tagline goes in the publish description instead.
die "no <title> in index.html\n" unless $html =~ m{<title>.*?</title>}s;
my $title = '<title>DEVI Collections</title>';

my ($fontlinks) = $html =~ m{(<link rel="preconnect".*?rel="stylesheet">)}s;
die "could not find the font links\n" unless $fontlinks;

# ---- inline the stylesheets, in the order index.html lists them -----------
my @sheets;
push @sheets, $1 while $html =~ m{<link rel="stylesheet" href="styles/([^"]+)">}g;
die "no local stylesheets found\n" unless @sheets;

my $css = '';
for my $s (@sheets) {
  $css .= "\n/* ================= styles/$s ================= */\n";
  $css .= slurp("$APP/styles/$s");
}

# ---- the body ---------------------------------------------------------------
my ($body) = $html =~ m{<body>(.*)</body>}s;
die "could not find <body>\n" unless $body;

# The module entry stays a real file reference; everything it imports is
# published alongside it.
$body =~ s{\s*<script type="module" src="app\.js"></script>}{}s;

my $out = <<"HEAD";
$title
<meta name="claude:viewport-fit-sides" content="cover">
<meta name="description" content="Hand-blocked bed linen, decorative artefacts, kurtis, utility goods and bags. A premium Indian lifestyle brand.">
$fontlinks
<style>
/* Generated by tools/mkartifact.pl from app/styles/*.css -- do not edit here.
   Edit the real stylesheets and run the script again. */
$css
</style>
$body
<script type="module" src="app.js"></script>
HEAD

open my $fh, '>:encoding(UTF-8)', "$OUT/artifact.html" or die "cannot write: $!\n";
print $fh $out;
close $fh;

my $kb = int((-s "$OUT/artifact.html") / 1024);
printf "built build/artifact.html  (%d KB, %d stylesheets inlined: %s)\n",
  $kb, scalar @sheets, join(', ', @sheets);

# A loud guard: the wrapper tags must not survive into the fragment.
# ⚠️ Anchored, so <header> and class="sec-head" are not false positives. The
# first version of this guard matched "<head" inside "<header" and refused to
# build a perfectly good fragment.
for my $tag ('<!doctype', '<html', '<head>', '<head ', '<body>', '<body ',
             '</html>', '</head>', '</body>') {
  if (lc($out) =~ /\Q$tag\E/) {
    print "FAIL  the fragment still contains $tag -- the host supplies that\n";
    exit 1;
  }
}
print "ok    no skeleton tags in the fragment\n";
exit 0;
